/** All languages of one key as Text (missing languages fall back to English at render time). */
export function T(key: string): Text {
  const out: Text = {};
  for (const [lang, s] of Object.entries(FRAUD_STRINGS) as [LangCode, Record<string, string>][]) if (s[key] !== undefined) out[lang] = s[key];
  return out;
}

/** One key in one language, with {vars} filled. */
export function ft(lang: LangCode, key: string, vars?: Record<string, string | number>): string {
  let s = FRAUD_STRINGS[lang]?.[key] ?? FRAUD_STRINGS['en-IN'][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
