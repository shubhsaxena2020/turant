// node shots.mjs <url> <outdir> <lang> : sample flow screenshots at 390x844 @2x
import { chromium } from 'playwright-core';
import { readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';
const [url, out, lang = 'hi-IN'] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const base = join(homedir(), 'AppData', 'Local', 'ms-playwright');
const dir = readdirSync(base).filter((d) => /^chromium-\d+$/.test(d)).sort().reverse()[0];
const exe = ['chrome-win64', 'chrome-win'].map((s) => join(base, dir, s, 'chrome.exe')).find(existsSync);
const b = await chromium.launch({ executablePath: exe });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })).newPage();
await p.addInitScript((l) => { try { localStorage.setItem('turant.lang', l); } catch {} window.speechSynthesis && (window.speechSynthesis.speak = (u) => setTimeout(() => u.onend && u.onend(new Event('end')), 300)); }, lang);
await p.goto(url, { waitUntil: 'networkidle' });
await p.waitForTimeout(800);
await p.screenshot({ path: join(out, '01-start.png') });
await p.click('[data-testid="sample"]');
await p.waitForTimeout(2500);
await p.screenshot({ path: join(out, '02-listening.png') });
await p.waitForSelector('[data-testid="letter"]', { timeout: 30000 });
await p.waitForTimeout(3500);
await p.screenshot({ path: join(out, '03-question.png') });
await p.waitForSelector('[data-testid="all-right"]', { timeout: 120000 });
await p.waitForTimeout(800);
await p.screenshot({ path: join(out, '04-check.png') });
await p.click('[data-testid="all-right"]');
await p.waitForTimeout(1500);
await p.screenshot({ path: join(out, '05-done.png') });
await p.click('[data-testid="see-written"]');
await p.waitForTimeout(1200);
await p.screenshot({ path: join(out, '06-document.png') });
await b.close();
console.log('ok');
